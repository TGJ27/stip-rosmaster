// STIP dashboard inspection overlays: ONLY visualize geometry from working ROS packages.
function overlayPoints(points) {
    if (!Array.isArray(points) || points.length !== 4 || !points.every(p => Array.isArray(p) && p.length===2 && p.every(Number.isFinite))) return '';
    return points.map(p => p[0]+','+p[1]).join(' ');
}
function overlayRect(box) {
    return [[box.x1,box.y1],[box.x2,box.y1],[box.x2,box.y2],[box.x1,box.y2]];
}
function updatePatrolInspection() {
    const r=state.status.ros || {};
    const qr=r.inspection_geometry, fire=r.fire_detections;
    // A single geometry pass applies equally to the compact preview and
    // expanded RGB stream. No synthetic boxes are generated by the browser.
    const source=(qr && qr.width && qr.height)?qr:(fire && fire.width && fire.height)?fire:null;
    ['#liveInspectionOverlay','#expandedCameraOverlay'].forEach(selector=>{
        const svg=$(selector);
        if(!svg)return;
        if(!source){svg.innerHTML='';svg.removeAttribute('viewBox');return;}
        const w=source.width,h=source.height, sw=Math.max(2,Math.round(w/300));
        svg.setAttribute('viewBox',`0 0 ${w} ${h}`);
        const polygons=[];
        const add=(pts,color)=>{
            const value=overlayPoints(pts);
            if(value)polygons.push(`<polygon points="${value}" fill="none" stroke="${color}" stroke-width="${sw}" stroke-linejoin="round"/>`);
        };
        if(qr && qr.width===w && qr.height===h){add(qr.qr,'#37eb80');add(qr.indicator,'#f6c35d');}
        if(fire && fire.width===w && fire.height===h)(fire.boxes||[]).forEach(box=>add(overlayRect(box),box.class_id===0?'#ff515e':'#ffb347'));
        svg.innerHTML=polygons.join('');
    });
    const results=$('#inspectionResults'), count=$('#inspectionResultCount');
    const items=(r.inspection_results || []).slice(-12).reverse();
    if(count) count.textContent=String(items.length);
    if(results) {
        const key=JSON.stringify(items);
        if(results.dataset.key!==key) {
            results.dataset.key=key;
            results.innerHTML=items.map(e=>`<div class="inspection-result"><b class="${e.status==='PASS'?'good':'bad'}">${esc(e.status)}</b> <span class="muted">${esc(e.timestamp||'')} · ${esc(e.waypoint||'')}</span><div>${esc(e.profile||'')} — ${esc(e.detail||'')}</div></div>`).join('')||'<span class="muted">No inspection result yet. Results appear after a QR task finishes.</span>';
        }
    }
    const eventLog=$('#patrolEventLog');
    if(eventLog){
        const entries=(state.status.events||[]).slice(-65).reverse();
        const key=JSON.stringify(entries);
        if(eventLog.dataset.key!==key){
            eventLog.dataset.key=key;
            eventLog.innerHTML=entries.map(e=>`<div class="patrol-event-line">${esc(e)}</div>`).join('') || '<span class="muted">No events yet.</span>';
        }
    }
    const st=$('#patrolFireStatus');
    if(st) {
        const fault = String(r.fire_state || '').indexOf('UNVERIFIED_')===0;
        st.textContent=r.confirmed?'CONFIRMED FIRE':r.fire_hold?(fault?'MONITOR FAULT':'INSPECTION HOLD'):r.fire?'MONITORING':'OFF';
        st.className=r.confirmed?'bad':r.fire_hold?'warntext':'good';
    }
    const explanation=$('#patrolFireDetail');
    if(explanation) {
        const cause = r.fire_state || 'UNKNOWN';
        explanation.textContent = r.fire_hold ?
           ('Motion stopped by ROS fire inspection ('+cause+'). It will not restart automatically.') :
           (r.fire ? 'Detector on · inspection state: '+cause : 'Fire monitoring off · no unconfirmed fire hold');
    }
    const f=r.fire_fusion || {};
    const tracking=$('#fireTrackingStatus'),trackDetail=$('#fireTrackingDetail');
    const detector=r.fire_detections||{}, boxes=detector.boxes||[];
    const fireTargets=boxes.filter(b=>b.class_id===0);
    const fusionState=String(r.fire_state||f.state||'UNKNOWN');
    const publishers=r.arm_publishers||[];
    const fireNode='/stip_fire_inspection';
    const competitors=publishers.filter(node=>node!==fireNode);
    let trackState='OFF',why='Fire monitoring disabled';
    if(r.fire){
        if(!f.auto_aim){
            trackState=state.fireTrackingPending?'WAITING':'DISABLED';
            why=state.fireTrackingPending?'Waiting for a safe stationary/paused acknowledgement':'ROS fire controller auto-aim not enabled';
        }else if(!fireTargets.length){
            trackState='NO FIRE TARGET';
            why='Auto-aim armed, but no fresh AI fire detection to follow';
        }else if(!f.navigation_pause_ack && !f.stationary_test_mode){
            trackState='WAITING FOR STOP';
            why='A fire target exists; waiting for ROS motion pause before moving arm';
        }else if(competitors.length){
            trackState='ARM BUSY';
            why='Another ROS node owns /TargetAngle: '+competitors.join(', ');
        }else if(!f.arm_pose_known){
            trackState='NO ARM FEEDBACK';
            why='Awaiting /ArmAngleUpdate or /CurrentAngle pose feedback';
        }else if(fusionState==='AIMING'){
            trackState='TRACKING';
            why='ROS fire controller is moving toward the AI target';
        }else if(fusionState==='SETTLING'){
            trackState='SETTLING';
            why='Waiting for servo movement to settle before thermal verification';
        }else if(fusionState==='AIM_LIMIT' || fusionState==='AIM_TIMEOUT'){
            trackState='TRACKING BLOCKED';
            why='ROS fire controller reports '+fusionState+'; check servo limits, tracking target and calibration';
        }else if(fusionState==='UNVERIFIED_TIMEOUT'){
            trackState='VERIFICATION TIMEOUT';
            why='AI fire target exists but ROS did not finish aiming/thermal verification. Check calibrated thermal FOV and arm control; no fire confirmed.';
        }else if(fusionState.indexOf('UNVERIFIED_')===0 || fusionState==='WAITING_SYNC'){
            trackState='UNVERIFIED';
            why='ROS fire state '+fusionState+'; tracking enabled does not imply a confirmed hot target';
        }else{
            trackState='ARMED';
            why='Controller state '+fusionState+' · '+fireTargets.length+' fire target(s); movement occurs only if target is off-center and safety checks pass';
        }
    }
    if(tracking)tracking.textContent=trackState;
    if(trackDetail)trackDetail.textContent=why;

    const temp=$('#fireTargetTemperature');
    if(temp)temp.textContent=Number.isFinite(r.fire_target_hot_c) ? r.fire_target_hot_c.toFixed(1)+' °C (target ROI)' : 'No verified target';
    const gas=$('#patrolGasStatus');if(gas)gas.textContent=(r.gas_raw === undefined?'—':r.gas_raw)+' / '+(r.gas_change_percent === undefined?'—':r.gas_change_percent+'%');
    const nav=$('#patrolNavStatus');if(nav)nav.textContent=r.nav||'—';
    const arm=$('#patrolArmStatus');if(arm)arm.textContent=Number((r.arm||{}).pan||0).toFixed(0)+'° / '+Number((r.arm||{}).tilt||0).toFixed(0)+'°';
    const acknowledge=$('#fireAcknowledge');
    if(acknowledge) {const enabled=!!(r.warning||r.confirmed||r.fire_hold);if(enabled && !acknowledge.firstElementChild)acknowledge.innerHTML=btn('Acknowledge Fire','fireClear()','warn s');else if(!enabled && acknowledge.firstElementChild)acknowledge.innerHTML='';}
}
function gasCalibrationPanel() {
    const r=state.status.ros||{}, healthy=!!((r.health||{}).gas), status=r.gas_calibration_status||'UNKNOWN';
    const baseline=r.gas_baseline===undefined?'—':r.gas_baseline;
    const collecting=status==='COLLECTING';
    return `<div class="metric"><span>Bridge</span><b class="${healthy?'good':'bad'}">${healthy?'READY':'OFFLINE'}</b></div>
    <div class="metric"><span>Raw ADC</span><b>${r.gas_raw===undefined?'—':esc(r.gas_raw)}</b></div>
    <div class="metric"><span>Baseline ADC</span><b>${esc(baseline)}</b></div>
    <div class="metric"><span>Calibration</span><b>${esc(status)}</b></div>
    <p class="gas-cal-note">Place the MQ-6 in known clean air and allow it to stabilize. This saves a <b>relative ADC baseline</b>, not ppm or %LEL. Not a certified gas alarm.</p>
    ${btn(collecting?'Collecting samples…':'Calibrate MQ-6','startGasCalibration()','blue s')}
    <div class="small muted" style="margin-top:8px">Uses existing /gas_sensor/calibrate service. Do not disconnect POP32i while collecting.</div>`;
}
async function startGasCalibration() {
    const r=state.status.ros||{};
    if(!((r.health||{}).gas))return toast('MQ-6 bridge is not ready',true);
    if(!confirm('The MQ-6 is stabilized in known clean air, away from gas sources. Start RELATIVE ADC baseline calibration? This does not calibrate ppm or %LEL.'))return;
    const result=await safe('gas_calibrate',{clean_air_confirmed:true});
    if(result)toast(result.message||'Collecting MQ-6 baseline samples');
}
